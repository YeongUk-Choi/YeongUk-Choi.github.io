#!/usr/bin/env python3
"""Generate browser X-ray form-factor data from Gemmi's neutral IT92 table.

Requires gemmi==0.7.5. Run with --check to verify the committed artifact.
Gemmi is needed only for regeneration, never by the static website.
"""

import argparse
import hashlib
import json
import math
from pathlib import Path

import gemmi


GEMMI_VERSION = "0.7.5"
OUTPUT = Path(__file__).resolve().parents[1] / "assets/js/rsm-factors.js"


def build_source():
    if gemmi.__version__ != GEMMI_VERSION:
        raise SystemExit("Regeneration requires gemmi==" + GEMMI_VERSION)

    coefficients = {}
    unsupported = []
    for number in range(1, 119):
        element = gemmi.Element(number)
        table = element.it92
        if table is None:
            unsupported.append(element.name)
            continue
        # Explicit properties preserve the documented order; get_coefs() uses
        # the same [a1..a4,b1..b4,c] layout with float32 conversion noise.
        values = list(table.a) + list(table.b) + [table.c]
        if len(values) != 9 or not all(math.isfinite(x) for x in values):
            raise SystemExit("Invalid coefficients for " + element.name)
        for got, expected in zip(values, table.get_coefs()):
            if not math.isclose(got, expected, rel_tol=1e-6, abs_tol=1e-7):
                raise SystemExit("Unexpected coefficient order for " + element.name)
        coefficients[element.name] = values
    # X-rays scatter from electrons, so Gemmi supplies H's coefficients for D.
    deuterium = gemmi.Element("D").it92
    coefficients["D"] = list(deuterium.a) + list(deuterium.b) + [deuterium.c]

    canonical = json.dumps(coefficients, separators=(",", ":"), ensure_ascii=True)
    digest = hashlib.sha256(canonical.encode("ascii")).hexdigest()
    rows = ["    " + json.dumps(key) + ": " + json.dumps(value) for key, value in coefficients.items()]
    metadata = {
        "model": "IT92 neutral-atom X-ray form factors",
        "gemmiVersion": GEMMI_VERSION,
        "coefficientOrder": ["a1", "a2", "a3", "a4", "b1", "b2", "b3", "b4", "c"],
        "coefficientSha256": digest,
        "source": "https://github.com/project-gemmi/gemmi/blob/v" + GEMMI_VERSION + "/include/gemmi/it92.hpp",
        "documentation": "https://gemmi.readthedocs.io/en/stable/scattering.html#x-ray-form-factors",
        "license": "MPL-2.0",
        "licenseUrl": "https://www.mozilla.org/MPL/2.0/",
        "maxStol2Exclusive": 4,
        "unsupportedElements": unsupported,
    }
    return """/* Generated by scripts/generate_rsm_factors.py using Gemmi %s.
 * Numerical coefficient table: Copyright 2019 Global Phasing Ltd.
 * SPDX-License-Identifier: MPL-2.0
 * License text: https://www.mozilla.org/MPL/2.0/
 * Source: https://github.com/project-gemmi/gemmi/blob/v%s/include/gemmi/it92.hpp
 * Origin: International Tables for Crystallography, Volume C (1992), IT92.
 * Neutral atoms H-Cf and D; original, unnormalized coefficients.
 * f0(s) = sum_i a_i exp(-b_i s^2) + c, s = sin(theta)/lambda in A^-1.
 * Valid range: 0 <= s < 2 A^-1. No anomalous or ionic corrections.
 * For q=1/d use stol2=q*q/4; for Q=2pi/d use stol2=(Q/(4pi))^2.
 * Unsupported atoms throw; they never receive a guessed scattering factor.
 */
(function (root, factory) {
  const api = factory();
  if (typeof module === "object" && module.exports) module.exports = api;
  else root.RsmFactors = api;
})(typeof self !== "undefined" ? self : this, function () {
  "use strict";
  const coefficients = {
%s
  };
  Object.values(coefficients).forEach(Object.freeze);
  Object.freeze(coefficients);
  const metadata = %s;
  Object.freeze(metadata.coefficientOrder);
  Object.freeze(metadata.unsupportedElements);
  Object.freeze(metadata);

  function supports(element) {
    return typeof element === "string" && Object.prototype.hasOwnProperty.call(coefficients, element);
  }

  function evaluate(element, stol2) {
    if (!supports(element)) throw new RangeError("No neutral IT92 X-ray coefficients for element: " + String(element));
    if (!Number.isFinite(stol2) || stol2 < 0 || stol2 >= metadata.maxStol2Exclusive) {
      throw new RangeError("IT92 requires 0 <= (sin(theta)/lambda)^2 < 4 A^-2");
    }
    const values = coefficients[element];
    let result = values[8];
    for (let i = 0; i < 4; i++) result += values[i] * Math.exp(-values[i + 4] * stol2);
    return result;
  }

  return Object.freeze({ coefficients, metadata, supports, evaluate });
});
""" % (GEMMI_VERSION, GEMMI_VERSION, ",\n".join(rows), json.dumps(metadata, indent=2).replace("\n", "\n  "))


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Compare generated content without writing")
    args = parser.parse_args()
    source = build_source()
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text(encoding="utf-8") != source:
            raise SystemExit("rsm-factors.js differs from Gemmi " + GEMMI_VERSION + " export")
        print("rsm-factors.js matches Gemmi " + GEMMI_VERSION)
    else:
        OUTPUT.write_text(source, encoding="utf-8")
        print("Generated " + str(OUTPUT))


if __name__ == "__main__":
    main()
