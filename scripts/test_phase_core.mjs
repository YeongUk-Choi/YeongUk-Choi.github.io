/* node scripts/test_phase_core.mjs
   Checks the phase viewer's crystallography against values that do not come
   from this program: cell volumes printed in the CIF, the site multiplicities
   implied by Z, rutile's systematic absences, and the published VO2 rutile <->
   monoclinic axis relation (402)_M1 = (002)_R, (201)_M1 = (001)_R. */
import { createRequire } from "node:module";
import { readFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const require = createRequire(import.meta.url);
const here = dirname(fileURLToPath(import.meta.url));
const P = require(join(here, "..", "assets", "js", "phase-core.js"));
const cache = JSON.parse(readFileSync(join(here, "..", "data", "phases", "VO2.json"), "utf8"));
const cif = id => {
  const e = cache.entries.find(x => String(x.cod_id) === String(id));
  if (!e) throw new Error("not in cache: " + id);
  return P.parseCif(e.cif);
};

let fails = 0;
const ok = (name, cond, detail) => {
  if (cond) console.log("  ok   " + name);
  else { fails++; console.log("  FAIL " + name + (detail ? "  -> " + detail : "")); }
};
const close = (got, want, tol) => Math.abs(got - want) <= tol;

console.log("CIF parsing and cell geometry");
{
  const m1 = cif(3000344);
  ok("M1 space group read", m1.spaceGroupNumber === 14, String(m1.spaceGroupNumber));
  ok("M1 cell a", close(m1.cell.a, 5.752316, 1e-6), String(m1.cell.a));
  ok("M1 beta", close(m1.cell.beta, 122.6112, 1e-6), String(m1.cell.beta));
  const V = P.volume(P.cellVectors(m1.cell));
  ok("M1 volume matches the CIF value 118.022", close(V, 118.022, 0.01), V.toFixed(4));
  ok("M1 e.s.d. stripped from 0.23890(24)", close(m1.atoms[0].x, 0.23890, 1e-6), String(m1.atoms[0].x));
}
{
  const m2 = cif(1521122);
  const V = P.volume(P.cellVectors(m2.cell));
  ok("M2 volume matches the CIF value 237.226", close(V, 237.226, 0.02), V.toFixed(4));
  ok("M2 has 8 C-centred operators", m2.symops.length === 8, String(m2.symops.length));
}

console.log("symmetry expansion");
{
  const m1 = cif(3000344);
  const at = P.expandAtoms(m1.atoms, m1.symops);
  const n = el => at.filter(a => a.element === el).length;
  /* Z = 4 formula units of VO2 in the P2_1/c cell. */
  ok("M1 expands to 4 V", n("V") === 4, String(n("V")));
  ok("M1 expands to 8 O", n("O") === 8, String(n("O")));
  const r = cif(1539951);
  const ar = P.expandAtoms(r.atoms, r.symops);
  ok("rutile expands to 2 V and 4 O", ar.filter(a => a.element === "V").length === 2 && ar.filter(a => a.element === "O").length === 4,
    ar.length + " atoms");
  /* The V at the body centre is generated by eight operators of P4_2/mnm; if
     duplicates were kept, every structure factor would be wrong. */
  ok("special positions are not duplicated", ar.length === 6, String(ar.length));
}

console.log("systematic absences (rutile P 4_2/m n m)");
{
  const r = cif(1539951);
  const A = P.cellVectors(r.cell);
  const at = P.expandAtoms(r.atoms, r.symops);
  const refl = P.reflections(A, at, { qmax: 1.4, maxIndex: 4 });
  const has = (h, k, l) => refl.some(x => x.h === h && x.k === k && x.l === l);
  ok("00l with l odd is absent (4_2 screw)", !has(0, 0, 1) && !has(0, 0, 3));
  ok("002 is present", has(0, 0, 2));
  ok("h00 with h odd is absent (n glide)", !has(1, 0, 0) && !has(3, 0, 0));
  ok("200 is present", has(2, 0, 0));
  ok("110 is present", has(1, 1, 0));
}

console.log("orientation relation R -> M1");
{
  const r = cif(1539951), m1 = cif(3000344);
  const m = P.matchLattice(r.cell, m1.cell, { maxIndex: 3, tol: 0.04 });
  ok("a match is found", !!m);
  if (m) {
    console.log("       P = " + JSON.stringify(m.P) + "   misfit " + (m.misfit * 100).toFixed(2) + " %   det " + m.det);
    ok("cell multiplicity is 2", m.det === 2, String(m.det));
    ok("misfit under 3 %", m.misfit < 0.03, (m.misfit * 100).toFixed(2) + " %");
    /* Rebuild the M1 cell on the rutile frame and confirm it reproduces the
       published monoclinic cell, not just a lattice of the right volume. */
    const Am = P.applyMatrix(m.P, P.cellVectors(r.cell));
    const got = P.cellFromVectors(Am);
    ok("rebuilt a ~ 5.75", close(got.a, m1.cell.a, 0.06), got.a.toFixed(4));
    ok("rebuilt b ~ 4.53", close(got.b, m1.cell.b, 0.06), got.b.toFixed(4));
    ok("rebuilt c ~ 5.38", close(got.c, m1.cell.c, 0.06), got.c.toFixed(4));
    ok("rebuilt beta ~ 122.6", close(got.beta, m1.cell.beta, 1.5), got.beta.toFixed(3));

    /* The published identification: the monoclinic (402) and (201) reflections
       sit on the rutile (002) and (001) positions. With A_M = P A_R the indices
       transform as h_M = P h_R, so the check is on indices, and separately on
       how far apart the two points actually land in the shared frame.

       Signs depend on which of the equivalent settings the search returned;
       (-4 0 2) is the Friedel mate of (4 0 -2) and describes the same relation,
       so the comparison is made up to an overall sign. */
    const Br = P.reciprocalVectors(P.cellVectors(r.cell));
    const Bm = P.reciprocalVectors(Am);
    const q = (B, hkl) => [0, 1, 2].map(i => hkl[0] * B[0][i] + hkl[1] * B[1][i] + hkl[2] * B[2][i]);
    const dist = (u, v) => P.norm([u[0] - v[0], u[1] - v[1], u[2] - v[2]]);
    const mul = (M, v) => M.map(row => row[0] * v[0] + row[1] * v[1] + row[2] * v[2]);
    const sameUpToSign = (u, v) => u.every((x, i) => x === v[i]) || u.every((x, i) => x === -v[i]);
    for (const [R, want] of [[[0, 0, 2], [4, 0, -2]], [[0, 0, 1], [2, 0, -1]]]) {
      const hM = mul(m.P, R);
      ok(`(${R.join("")})_R is (${want.join("")})_M1`, sameUpToSign(hM, want), "got (" + hM.join(" ") + ")");
      const d = dist(q(Bm, hM), q(Br, R));
      ok(`  and the two points coincide in the shared frame`, d < 0.02, d.toFixed(5) + " 1/A apart");
    }
  }
}

console.log("phase grouping");
{
  const recs = cache.entries.map(e => ({ id: String(e.cod_id), sgNumber: e.sg_number, cell: e }));
  const groups = P.groupPhases(recs).map(g => g.map(r => r.id));
  console.log("       " + groups.map(g => g.join("+")).join("   "));
  const same = (a, b) => groups.some(g => g.includes(a) && g.includes(b));
  ok("the two M1 papers group together", same("3000344", "9009089"));
  ok("the rutile papers group together", same("1539951", "1537412"));
  /* Both are C 2/m. Grouping on the space group alone would call the B phase M2. */
  ok("M2 and the B phase stay apart", !same("1521122", "1530870"));
}

console.log(fails ? `\n${fails} check(s) failed` : "\nall checks passed");
process.exit(fails ? 1 : 0);
